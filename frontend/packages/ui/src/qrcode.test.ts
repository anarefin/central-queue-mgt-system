describe("encodeQrMatrix", () => {
  it("matches a known-good version-1 QR for a short all-uppercase string", () => {
    expect(render(encodeQrMatrix("HELLO"))).toEqual(HELLO);
  });

  it("matches a known-good version-4 QR for a URL with query parameters", () => {
    expect(render(encodeQrMatrix("https://q/visitor/?t=1234567890AB&s=abcdefghijklmnopqrstuvwxyz012345"))).toEqual(SHORT_URL_V4);
  });

  it("matches a known-good version-6 QR for a longer visitor-ticket URL", () => {
    expect(render(encodeQrMatrix("https://kiosk.example.org/visitor/?t=8f14e45f-ceea-467e-b3b3-c6c6c6c6c6c6&s=k7Qw2f9Lm3Xn8Rt1Vy5Zp0Bq6Hj4Cd2Ee7Ff3Gg8Hh9Ii1Jj"))).toEqual(LONG_URL_V6);
  });

  it("produces a square matrix that grows with version and is deterministic", () => {
    const a = encodeQrMatrix("https://qms.example/visitor/?t=abc&s=def");
    const b = encodeQrMatrix("https://qms.example/visitor/?t=abc&s=def");
    expect(a.length).toBeGreaterThanOrEqual(21);
    expect(a.every((row) => row.length === a.length)).toBe(true);
    expect(a).toEqual(b);
  });

  it("rejects data too long to fit the supported version range", () => {
    expect(() => encodeQrMatrix("x".repeat(1000))).toThrow();
  });
});
